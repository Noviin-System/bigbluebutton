🔴 گزارش حل مشکل خطای میکروفون (رخداد سرور `sd014`,`sd013`,`sd012`)

📌 ریشه مشکل (Root Cause):  
به دلیل بروز *Race Condition* در زمان استارت‌آپ FreeSWITCH (پس از ری‌بوت سرور)، پروفایل‌های SIP روی IPv4 لود نشدند و سرویس پس از ۳ تلاش ناموفق متوقف شد. در نتیجه، سوکت‌های ارتباطی روی آی‌پی اصلی سرور بالا نیامده بودند و فقط لوپ‌بک IPv6 فعال بود که همین امر موجب تایم‌اوت شدن پل صوتی (FreeSWITCH Adapter) و خطای میکروفون کاربران شد.

🛠 اقدام اصلاحی فوری (Fix):  
با اجرای دستور زیر سرویس ری‌استارت شد و لیسنرهای IPv4 با موفقیت روی آی‌پی اصلی سرور قرار گرفتند:
sudo systemctl restart freeswitch

